/**
 * Display helper mapping country names and ISO 3166-1 alpha-2 codes to Unicode flag emojis.
 *
 * Covers all 275 country labels published in the Charity Commission register
 * (data/register.sqlite), plus common international aliases and ISO codes.
 */

/** Converts a 2-letter ISO 3166-1 alpha-2 code to its regional indicator flag emoji. */
export function isoToFlagEmoji(iso: string | null | undefined): string | null {
  if (!iso) return null;
  const trimmed = iso.trim().toUpperCase();
  if (trimmed.length !== 2) return null;
  const first = trimmed.charCodeAt(0);
  const second = trimmed.charCodeAt(1);
  if (first < 65 || first > 90 || second < 65 || second > 90) return null;
  return String.fromCodePoint(0x1f1e6 + first - 65, 0x1f1e6 + second - 65);
}

