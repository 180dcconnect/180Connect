/**
 * Returns the ISO 3166-1 alpha-2 code for a country name if recognized.
 */
export function countryToIso(country: string | null | undefined): string | null {
  if (!country) return null;
  const normalized = country.trim().toLowerCase();
  if (normalized.length === 2) return normalized.toUpperCase();
  return COUNTRY_TO_ISO[normalized] ?? null;
}

/**
 * Returns the Unicode flag emoji for a given country name or 2-letter ISO code.
 * Returns null if unrecognised.
 *
 * Examples:
 *   countryFlagEmoji("Kenya") -> "🇰🇪"
 *   countryFlagEmoji("Occupied Palestinian Territories") -> "🇵🇸"
 *   countryFlagEmoji("Congo (Democratic Republic)") -> "🇨🇩"
 *   countryFlagEmoji("Burma") -> "🇲🇲"
 *   countryFlagEmoji("Scotland") -> "🏴󠁧󠁢󠁳󠁣󠁴󠁿"
 */
export function countryFlagEmoji(country: string | null | undefined): string | null {
  if (!country) return null;
  const normalized = country.trim().toLowerCase();

  const special = SPECIAL_FLAGS[normalized];
  if (special) return special;

  // Direct 2-letter code check
  if (normalized.length === 2) {
    return isoToFlagEmoji(normalized);
  }

  const iso = COUNTRY_TO_ISO[normalized];
  if (iso) {
    return isoToFlagEmoji(iso);
  }

  return null;
}
